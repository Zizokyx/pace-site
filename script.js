  function rr(x, y, w, h, r) {
    ctx.beginPath();
    ctx.moveTo(x + r, y);
    ctx.arcTo(x + w, y, x + w, y + h, r);
    ctx.arcTo(x + w, y + h, x, y + h, r);
    ctx.arcTo(x, y + h, x, y, r);
    ctx.arcTo(x, y, x + w, y, r);
    ctx.closePath();
  }
  function glow(c, w) {
    ctx.strokeStyle = c;
    ctx.lineWidth = w;
    ctx.shadowColor = c;
    ctx.shadowBlur = 10;
  }
  function noGlow() {
    ctx.shadowBlur = 0;
  }

