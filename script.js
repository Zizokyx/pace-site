const cinematicSection = document.querySelector(".cinematic-digital");

const cinematicFrames = document.querySelectorAll(".cinematic-frame");

const progressBar = document.querySelector(".cinematic-progress i");

function updateCinematicSection() {
  if (!cinematicSection) return;

  const rect = cinematicSection.getBoundingClientRect();

  const total = cinematicSection.offsetHeight - window.innerHeight;

  const passed = Math.min(Math.max(-rect.top, 0), total);

  const progress = total > 0 ? passed / total : 0;

  cinematicFrames.forEach((frame, index) => {
    const start = index / (cinematicFrames.length - 1);

    const distance = Math.abs(progress - start);

    const opacity = Math.max(0, 1 - distance * 4);

    const scale = 1.12 - opacity * 0.12;

    const blur = (1 - opacity) * 18;

    frame.style.opacity = opacity;

    frame.style.transform = `scale(${scale})`;

    frame.style.filter = `blur(${blur}px)`;
  });

  if (progressBar) {
    progressBar.style.width = `${progress * 100}%`;
  }
}

window.addEventListener("scroll", updateCinematicSection);

window.addEventListener("resize", updateCinematicSection);

updateCinematicSection();

