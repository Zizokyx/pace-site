// ---- Demo carousels: FIECARE .demo-carousel e un carusel INDEPENDENT ----
// (înainte, toate slide-urile din toate modalele erau tratate ca un singur
//  carusel, așa că cele din modalul Automation/AI ajungeau mereu .hidden)
document.querySelectorAll(".demo-carousel").forEach((carousel) => {
  const slides = carousel.querySelectorAll(".demo-slide");
  const tabs = carousel.querySelectorAll(".demo-tab");
  if (!slides.length) return;

  const n = slides.length;
  let active = 0;

  function render() {
    slides.forEach((slide, i) => {
      slide.classList.remove("active", "prev", "next", "hidden");

      if (i === active) {
        slide.classList.add("active");
      } else if (i === (active + 1) % n) {
        slide.classList.add("next");
      } else if (i === (active - 1 + n) % n) {
        slide.classList.add("prev");
      } else {
        slide.classList.add("hidden");
      }
    });

    tabs.forEach((tab, i) => {
      tab.classList.toggle("active", i === active);
    });
  }

  slides.forEach((slide, i) => {
    slide.addEventListener("click", () => {
      active = i;
      render();
    });
  });

  tabs.forEach((tab, i) => {
    tab.addEventListener("click", () => {
      active = i;
      render();
    });
  });

  render();
});

